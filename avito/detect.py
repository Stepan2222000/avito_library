"""Детекторы страниц Авито: что нам вообще прислали.

Правила, одинаковые для всех детекторов:

  * один детектор — один маркер. Разметка Авито постоянна, узел сам по себе является
    признаком, и набор из пяти подстрок «на всякий случай» только прячет тот момент,
    когда признак перестал работать;
  * детектор отвечает «да» или «нет» и больше ничего. Ни данных, ни разобранного
    состояния наружу не отдаёт — разбор живёт отдельно, в avito/parse.py;
  * маркер ищется точной подстрокой по всему телу. Дерево не поднимаем: результат тот
    же, а страницы у нас по три мегабайта, и поиск подстроки на них стоит около
    миллисекунды против десятков на разбор DOM;
  * каждый маркер проверен на всём корпусе сохранённых страниц — tmp/check_detect.py.
    Пересечений между детекторами быть не должно, это и доказывает, что одного
    маркера достаточно.
"""
from __future__ import annotations

__all__ = ["МАРКЕР_КАТАЛОГА", "МАРКЕР_КАРТОЧКИ", "МАРКЕР_БАРЬЕРА", "МАРКЕР_ЗАДАЧИ",
           "МАРКЕР_КАПЧИ", "МАРКЕР_ВЫДАЧИ", "МАРКЕР_ЗАГЛУШКИ",
           "каталог", "карточка", "барьер", "задача", "капча", "выдача", "заглушка"]

# Узел выдачи. Проверено на 65 страницах: есть на всех 35 каталогах, включая
# автомобили, электронику, квартиры и вакансии, и отсутствует на всех остальных —
# на карточках, капче, таймере, заглушке и странице «не найдено».
МАРКЕР_КАТАЛОГА = 'data-marker="catalog-serp"'


def каталог(страница: str) -> bool:
    """Это страница выдачи с объявлениями?

    Пустая выдача сюда не попадает намеренно: на ней узла выдачи нет вовсе, хотя пара
    рекламных врезок с виду похожа на карточки. Отличить пустую выдачу от чужой
    страницы — забота отдельного детектора.
    """
    return МАРКЕР_КАТАЛОГА in страница


# Узел с номером объявления. Из 52 маркеров, что есть на всех карточках и больше нигде,
# выбран он: номер есть у любого объявления без исключений. Цена такую проверку тоже
# прошла, но завязываться на неё нельзя — у вакансий и отданного даром её не будет,
# просто такой образец нам не попался. То же с картой, характеристиками и кнопкой
# сообщений: любое из этого пропадает на конкретном объявлении, а номер — нет.
МАРКЕР_КАРТОЧКИ = 'data-marker="item-view/item-id"'


def карточка(страница: str) -> bool:
    """Это страница объявления?

    Снятое объявление, которое Авито уводит редиректом в журнал, сюда не попадёт —
    карточки там нет вовсе. А вот страница «снято с публикации», где объявление
    отрисовано целиком, считается карточкой намеренно: данные на ней настоящие, а
    сам факт снятия — это поле is_active, а не тип страницы.
    """
    return МАРКЕР_КАРТОЧКИ in страница


# Заголовок страницы файрвола. Проверено: ровно на 24 барьерных страницах корпуса, и
# больше эта фраза не встречается нигде — ни в тексте, ни в скриптах.
МАРКЕР_БАРЬЕРА = "<title>Доступ ограничен"


def барьер(страница: str) -> bool:
    """Нас остановил файрвол?

    Барьер бывает трёх видов, и различают их два детектора ниже. Таймер собственного
    признака не имеет — искал специально, всё своеобразное у него сводится к пустым
    `container` и `icon`. Поэтому таймер определяется по остатку: барьер есть, а ни
    задачи, ни формы на нём нет. Действие при этом безопасное — увести адрес отдыхать.
    """
    return МАРКЕР_БАРЬЕРА in страница


# Блок с кружком на странице проверки безопасности. Своя разметка: pow-spinner,
# pow-status, firewall-spinner. Проверено на четырёх таких страницах.
МАРКЕР_ЗАДАЧИ = 'id="pow-status"'


def задача(страница: str) -> bool:
    """Барьер решается перебором хеша?

    Это та самая белая страница с крутящимся кружком и надписью «Выполняется проверка».
    Не путать с заглушкой «Подождите, идет загрузка»: там кружок означает ровно
    обратное — что адрес выдохся.
    """
    return МАРКЕР_ЗАДАЧИ in страница


# Форма файрвола с галочкой. Есть на всех капчах корпуса, включая пять снятых с разных
# прокси, и отсутствует на таймере и на странице задачи.
МАРКЕР_КАПЧИ = "js-firewall-form"


def капча(страница: str) -> bool:
    """Барьер решается капчей?

    Только про наличие формы. Решится ли она на самом деле — вопрос к решателю: капча
    привязана к адресу и сессии и с чужого адреса не принимается.
    """
    return МАРКЕР_КАПЧИ in страница


# Счётчик «сколько нашлось» в шапке выдачи. Ровно на 43 страницах корпуса: все 42
# каталога и пустая выдача. На карточках, барьерах и «не найдено» его нет.
МАРКЕР_ВЫДАЧИ = 'data-marker="page-title/count"'


def выдача(страница: str) -> bool:
    """Это страница выдачи — неважно, нашлось на ней что-нибудь или нет?

    В паре с детектором каталога даёт пустую выдачу: страница выдачи есть, а узла с
    объявлениями нет. Складывает эти два ответа вызывающий — сами детекторы друг о
    друге не знают.
    """
    return МАРКЕР_ВЫДАЧИ in страница


# Мета-обновление через секунду. Ровно на двух страницах корпуса, и обе — заглушки.
МАРКЕР_ЗАГЛУШКИ = 'http-equiv="refresh"'


def заглушка(страница: str) -> bool:
    """Нас выпихнули на главную?

    Белая страница со словами «Подождите, идет загрузка», которая сама себя обновляет
    через секунду. Приходит и с обычным 200, и с 302 без адреса в заголовке. Означает
    не то, что объявления нет, а то, что наш адрес на исходе: принять её за конец среза
    или за снятое объявление — значит похоронить живые данные.

    Образцов у неё пока всего два, и это одна и та же страница с разных адресов.
    """
    return МАРКЕР_ЗАГЛУШКИ in страница
