def применено(состояние: dict) -> dict[int, object]:
    """Что страница считает выставленным. Ни одного запроса: всё уже в ответе."""
    данные = состояние.get("loaderData", {}).get("data", состояние)
    из: dict[int, object] = {}

    def пусто(зн) -> bool:
        if зн in (None, [], {}, "", False):
            return True
        if isinstance(зн, dict):
            return all(v in (None, "") for v in зн.values())
        return False

    def обойти(узлы):
        for ф in узлы:
            номер, зн = ф.get("attrId"), ф.get("currentValue")
            if номер and not пусто(зн):
                из[номер] = зн
            for ключ in ("content", "filters"):
                if isinstance(ф.get(ключ), list):
                    обойти(ф[ключ])

    for раздел in (данные.get("filtersV2") or {}).get("Sections") or []:
        обойти(раздел.get("Filters") or [])
    return из


def _одинаково(ждали, получили) -> bool:
    if isinstance(ждали, dict):
        если_число = lambda x: None if x in (None, "") else int(x)  # noqa: E731
        try:
            return (если_число((получили or {}).get("from")) == если_число(ждали.get("from"))
                    and если_число((получили or {}).get("to")) == если_число(ждали.get("to")))
        except (TypeError, ValueError):
            return False
    было = получили if isinstance(получили, list) else [получили]
    try:
        return sorted(int(x) for x in было) == sorted(int(x) for x in ждали)
    except (TypeError, ValueError):
        return False


def сверить(собранное: Собранное, состояние: dict) -> list[str]:
    """Чего из запрошенного Авито не выставил. Пустой список — всё в порядке.

    Проверять обязательно: фильтр может не примениться молча, и тогда мы обойдём
    совсем не тот срез, ничего не заподозрив.
    """
    выставлено = применено(состояние)
    беды = []
    for номер, ждали in собранное.ожидаем.items():
        получили = выставлено.get(номер)
        if получили is None:
            беды.append(f"фильтр {номер} не применился вовсе")
        elif not _одинаково(ждали, получили):
            беды.append(f"фильтр {номер}: ждали {ждали}, а выставлено {получили}")
    return беды
