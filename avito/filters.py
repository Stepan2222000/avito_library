"""Фильтры выдачи: справочник значений и сборка компактного кода `f=`.

Авито давно не понимает фильтры в виде `params[...]` в адресе страницы — они работают
только на внутренней json-ручке. На обычных страницах фильтр едет одним компактным
кодом, и этот модуль умеет его собирать сам.

Устройство кода разобрано по настоящим ссылкам Авито и проверено побайтово на девяти
эталонах, покрывающих все три вида фильтров и их смесь:

    01 28                       неизменное начало
    [a][b][c] 02                четыре флажка: 1 — такой вид фильтров в коде есть, 2 — нет
                                a — выбор одного значения, b — выбор нескольких, c — диапазон
    [сколько] 44  (фильтр, значение)…            числа — удвоенные номера, варинтами
    [сколько] 40  (фильтр, 16k+4, значения…)     выбор k значений одного фильтра
    [сколько] 45  (фильтр, длина, {"from":…,"to":…})   диапазон, внутри обычный JSON

Две особенности, на которых легко обжечься. В диапазоне обязательны оба ключа: если
границы нет, надо писать null, иначе код не примут. И в base64 Авито использует `~`
там, где обычно стоит подчёркивание.

Номера значений берутся из самой страницы — отдельный запрос за ними не нужен. Но
доверять им до конца нельзя: у турбины, например, страница показывает один номер, а в
ссылке работает совсем другой, и с «правильным» номером фильтр просто не применяется.
Поэтому после запроса надо свериться, что Авито выставил именно то, что мы просили, —
это делает `сверить`, и сети она не требует. Без такой сверки мы спокойно обойдём не
тот срез и ничего не заметим.
"""
from __future__ import annotations

import base64
import dataclasses
import json

from avito.errors import НетТакогоФильтра, УпрямыйФильтр

__all__ = ["Фильтр", "Справочник", "Собранное", "НетТакогоФильтра", "УпрямыйФильтр",
           "справочник", "код", "собрать", "применено", "сверить"]

ВЫБОР, ДИАПАЗОН = "выбор", "диапазон"

# Фильтры, которые в компактном коде не работают. Проверено вживую: страница отдаётся
# как ни в чём не бывало, а фильтра в ней нет. Лучше отказать заранее, чем обойти не то.
#
# У турбины причина известна и любопытная: страница объявляет значение «Есть» под
# номером 18628808, но применяется оно только под 18759880 — ровно на 131072 больше.
# Общим правилом это не оказалось: у «Количества мест» номер такой же длинный и
# работает как есть, а тот же сдвиг ломает и его, и привод. Так что подобрать номер
# турбины из справочника нечем.
УПРЯМЫЕ = {2687: "Пробег", 147411: "Кузов", 161208: "Турбина"}


@dataclasses.dataclass(slots=True)
class Фильтр:
    номер: int
    имя: str
    вид: str                      # ВЫБОР или ДИАПАЗОН
    значения: dict[int, str] = dataclasses.field(default_factory=dict)

    def код_значения(self, что) -> int:
        if isinstance(что, int) and что in self.значения:
            return что
        для_поиска = str(что).strip().lower()
        for код_, имя in self.значения.items():
            if (имя or "").strip().lower() == для_поиска:
                return код_
        raise НетТакогоФильтра(
            f"у фильтра «{self.имя}» нет значения «{что}»; есть: "
            + ", ".join(sorted(filter(None, self.значения.values()))[:12]))


@dataclasses.dataclass(slots=True)
class Справочник:
    фильтры: dict[int, Фильтр]

    def найти(self, что) -> Фильтр:
        if isinstance(что, int):
            if что in self.фильтры:
                return self.фильтры[что]
            raise НетТакогоФильтра(f"фильтра с номером {что} на странице нет")
        для_поиска = str(что).strip().lower()
        for ф in self.фильтры.values():
            if (ф.имя or "").strip().lower() == для_поиска:
                return ф
        raise НетТакогоФильтра(f"фильтра «{что}» на странице нет")

    def __len__(self) -> int:
        return len(self.фильтры)


def справочник(состояние: dict) -> Справочник:
    """Достаёт из состояния страницы каталога номера фильтров и коды их значений.

    Состояние — то, что отдаёт avito.parse.состояние_выдачи. Отдельный запрос не нужен:
    справочник лежит в любой странице выдачи, которую мы и так качаем.
    """
    данные = состояние.get("loaderData", {}).get("data", состояние)
    разделы = (данные.get("filtersV2") or {}).get("Sections") or []
    если_нет = not разделы
    if если_нет:
        raise НетТакогоФильтра("в состоянии страницы нет описания фильтров")

    из: dict[int, Фильтр] = {}

    def значения_из(ф) -> dict[int, str]:
        """Значения бывают списком, а бывают разложены по группам.

        У марок, коробки и страны бренда values — это не значения, а разделы, и сами
        значения лежат внутри в options: марок так набирается 437 против нуля, если
        смотреть только верхний список.
        """
        из = {}
        for v in ф.get("values") or []:
            if not isinstance(v, dict):
                continue
            if str(v.get("value", "")).isdigit():
                из[int(v["value"])] = v.get("name") or ""
            for o in v.get("options") or []:
                if isinstance(o, dict) and str(o.get("value", "")).isdigit():
                    из[int(o["value"])] = o.get("name") or ""
        return из

    def обойти(узлы):
        for ф in узлы:
            номер = ф.get("attrId")
            if номер:
                значения = значения_из(ф)
                вид = ДИАПАЗОН if "range" in (ф.get("type") or "").lower() else ВЫБОР
                прежний = из.get(номер)
                # один и тот же фильтр встречается в нескольких разделах; берём тот
                # экземпляр, у которого есть значения
                if прежний is None or (значения and not прежний.значения):
                    из[номер] = Фильтр(номер, ф.get("defaultTitle") or ф.get("title") or "",
                                       вид, значения)
            for ключ in ("content", "filters"):
                if isinstance(ф.get(ключ), list):
                    обойти(ф[ключ])

    for раздел in разделы:
        обойти(раздел.get("Filters") or [])
    return Справочник(из)


# ------------------------------------------------------------------ сборка кода

def _варинт(n: int) -> bytes:
    из = bytearray()
    while True:
        байт = n & 0x7F
        n >>= 7
        из.append(байт | (0x80 if n else 0))
        if not n:
            return bytes(из)


def код(одиночные=(), множественные=(), диапазоны=()) -> str:
    """Собирает компактный код из номеров. Низкий уровень, без справочника.

    одиночные:     [(фильтр, значение), ...]
    множественные: [(фильтр, [значения]), ...]
    диапазоны:     [(фильтр, от, до), ...] — любая граница может быть None
    """
    # порядок внутри группы фиксируем, чтобы один и тот же запрос давал один и тот же
    # код: иначе его не сравнить ни с прошлым прогоном, ни с ссылкой самого Авито
    одиночные = sorted(одиночные)
    множественные = sorted(множественные)
    диапазоны = sorted(диапазоны)

    тело = bytearray([1, 0x28])
    тело += bytes([1 if одиночные else 2, 1 if множественные else 2,
                   1 if диапазоны else 2, 2])
    if одиночные:
        тело += bytes([len(одиночные), 0x44])
        for фильтр, значение in одиночные:
            тело += _варинт(фильтр * 2) + _варинт(значение * 2)
    if множественные:
        тело += bytes([len(множественные), 0x40])
        for фильтр, значения in множественные:
            тело += _варинт(фильтр * 2) + bytes([16 * len(значения) + 4])
            for з in значения:
                тело += _варинт(з * 2)
    if диапазоны:
        тело += bytes([len(диапазоны), 0x45])
        for фильтр, от, до in диапазоны:
            # оба ключа обязательны, пустую границу пишем как null
            строка = json.dumps({"from": от, "to": до}, separators=(",", ":")).encode()
            тело += _варинт(фильтр * 2) + _варинт(len(строка)) + строка
    return base64.urlsafe_b64encode(bytes(тело)).decode().rstrip("=").replace("_", "~")


@dataclasses.dataclass(slots=True)
class Собранное:
    код: str
    ожидаем: dict[int, object]    # номер фильтра -> что должно оказаться выставленным
    описание: str                 # человеческими словами, для журнала и базы

    def __str__(self) -> str:
        return self.описание


def собрать(спр: Справочник, запрос: dict, *, разрешить_упрямые: bool = False) -> Собранное:
    """Собирает код по человеческому запросу.

    Запрос — {название фильтра: значение}, где значение это:
      одно значение          «Полный» или его номер,
      несколько значений     ["Полный", "Задний"],
      диапазон               (2015, 2020), (None, 50000) или {"от": 200, "до": 400}.
    """
    одиночные, множественные, диапазоны = [], [], []
    ожидаем: dict[int, object] = {}
    словами = []

    for ключ, значение in запрос.items():
        ф = спр.найти(ключ)
        if ф.номер in УПРЯМЫЕ and not разрешить_упрямые:
            raise УпрямыйФильтр(
                f"фильтр «{ф.имя}» в компактном коде не применяется — проверено вживую. "
                f"Пока обходите его другим срезом; разрешить принудительно можно "
                f"флагом «разрешить_упрямые»")

        if isinstance(значение, dict) and ("от" in значение or "до" in значение):
            значение = (значение.get("от"), значение.get("до"))
        диапазон_ли = ф.вид == ДИАПАЗОН or (
            isinstance(значение, tuple) and len(значение) == 2)

        if диапазон_ли:
            от, до = значение if isinstance(значение, tuple) else (значение, None)
            диапазоны.append((ф.номер, от, до))
            ожидаем[ф.номер] = {"from": от, "to": до}
            словами.append(f"{ф.имя} {от if от is not None else '…'}–{до if до is not None else '…'}")
        elif isinstance(значение, (list, set)):
            коды = sorted(ф.код_значения(з) for з in значение)
            if len(коды) == 1:
                одиночные.append((ф.номер, коды[0]))
            else:
                множественные.append((ф.номер, коды))
            ожидаем[ф.номер] = коды
            словами.append(f"{ф.имя}: " + ", ".join(ф.значения.get(к, str(к)) for к in коды))
        else:
            к = ф.код_значения(значение)
            одиночные.append((ф.номер, к))
            ожидаем[ф.номер] = [к]
            словами.append(f"{ф.имя}: {ф.значения.get(к, значение)}")

    return Собранное(код(одиночные, множественные, диапазоны), ожидаем, "; ".join(словами))


