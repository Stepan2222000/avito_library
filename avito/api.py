"""Вход в библиотеку: класс `Авито` и его задачи.

Задач три: посмотреть, какие бывают фильтры; забрать выдачу каталога; забрать карточки
объявлений по номерам. Ни срезов, ни курсоров, ни очередей здесь нет — задача делает
ровно то, о чём попросили, и возвращает результат.

Работаем жёстко. Барьеры, обрывы и смена адреса — обычная работа и наружу не выходят:
проверку безопасности решаем, капчу решаем, на таймере меняем адрес, обрыв повторяем.
А вот всё, после чего продолжать нельзя без риска записать неправду, роняет задачу
сразу — см. avito.errors.

Адресами библиотека не распоряжается: она просит их у поставщика и сообщает ему исход.
Страницы на диск не складывает и в консоль не печатает — отдаёт события наблюдателю,
кому надо, тот и пишет.
"""
from __future__ import annotations

import dataclasses
import datetime as dt
import re
from collections.abc import Callable, Iterable
from typing import Protocol

from avito import barriers, detect, filters
from avito.errors import (АдресаКончились, НеопознаннаяСтраница, ОбъявлениеСнято,
                          ФильтрНеПрименился)
from avito.parse import разобрать_выдачу, разобрать_карточку, состояние_выдачи
from avito.store import Склад

BASE = "https://www.avito.ru"
ПОВТОРОВ_НА_ОБРЫВЕ = 3

__all__ = ["Авито", "Выдача", "Карточки", "Событие", "Адрес", "Адреса"]


class Адрес(Protocol):
    """Адрес, с которого ходим. Что за ним стоит — дело поставщика.

    Сессия обязана следовать редиректам: библиотека смотрит только на конечную страницу.
    """
    имя: str
    сессия: object     # что-то с get, post и куками — например curl_cffi.AsyncSession


class Адреса(Protocol):
    """Поставщик адресов. Живёт снаружи: он знает про списки, качество и остывание.

    Исходы, которые ему сообщают: «прошло», «таймер», «капча», «заглушка», «молчит».
    """

    async def взять(self) -> Адрес | None: ...

    async def вернуть(self, адрес: Адрес, исход: str) -> None: ...


@dataclasses.dataclass(slots=True)
class Событие:
    """Что произошло. Тело страницы прикладывается — библиотека его не сохраняет."""
    вид: str                    # 'страница' | 'барьер' | 'адрес выбыл' | 'обрыв' | 'записано'
    ссылка: str
    состояние: str = ""
    код: int | None = None
    адрес: str = ""
    тело: str | None = None
    подробности: str = ""
    объявлений: int = 0


@dataclasses.dataclass(slots=True)
class Выдача:
    объявления: list[dict]
    всего: int | None = None            # сколько нашлось по мнению Авито
    страниц_всего: int | None = None    # докуда пускают листать
    страницы: list[int] = dataclasses.field(default_factory=list)
    фильтр: str | None = None           # словами, как просили
    сортировка: str | None = None       # словами же
    запросов: int = 0

    def __len__(self) -> int:
        return len(self.объявления)


@dataclasses.dataclass(slots=True)
class Карточки:
    карточки: list[dict]
    запросов: int = 0

    def __len__(self) -> int:
        return len(self.карточки)


def _номер_страницы(ссылка: str) -> int | None:
    m = re.search(r"[?&]p=(\d+)", ссылка or "")
    return int(m.group(1)) if m else None


def _путь(ссылка: str) -> str:
    без_схемы = re.sub(r"^https?://[^/]+", "", ссылка or "")
    return без_схемы.split("?")[0].rstrip("/") or "/"


class Авито:
    def __init__(self, адреса: Адреса, склад: Склад | None = None,
                 наблюдатель: Callable[[Событие], None] | None = None):
        self.адреса = адреса
        self.склад = склад
        self._сказать = наблюдатель or (lambda с: None)
        self._адрес: Адрес | None = None
        self._запросов = 0

    # ------------------------------------------------------------------ задачи

    async def фильтры(self, путь: str) -> filters.Справочник:
        """Какие фильтры бывают у этой категории и какие у них значения.

        Отдельного запроса за справочником не существует: он лежит в обычной странице
        выдачи, которую мы и так качаем.
        """
        тело, _, _ = await self._страница(путь)
        if not detect.каталог(тело) and not detect.выдача(тело):
            raise НеопознаннаяСтраница(f"по адресу {путь} пришла не выдача")
        return filters.справочник(состояние_выдачи(тело))

    async def каталог(self, путь: str, *, фильтр: dict | None = None,
                      сортировка: str | int | None = None, страниц: int = 1,
                      с_какой: int = 1, писать: bool | None = None) -> Выдача:
        """Забрать страницы выдачи. Фильтр и сортировка задаются словами.

        Сортировка — «по дате», «дешевле», «дороже», «по умолчанию» или название из
        самой категории вроде «по году выпуска». За общими четырьмя на страницу ходить
        не надо, за остальными библиотека сама сходит за справочником — как и за
        фильтром, и если просят и то и другое, страница берётся одна на двоих.
        """
        собранное = None
        порядок = (filters.сортировка_без_справочника(сортировка)
                   if сортировка is not None else None)
        if фильтр or (сортировка is not None and порядок is None):
            спр = await self.фильтры(путь)
            if фильтр:
                собранное = filters.собрать(спр, фильтр)
            if сортировка is not None:
                # справочник уже в руках — переспрашиваем даже про угаданное: так
                # название в журнале будет авитовское, а выдуманная сортировка отвалится
                # до запроса, а не после
                порядок = спр.сортировка(сортировка)

        итог = Выдача(объявления=[], фильтр=собранное.описание if собранное else None,
                      сортировка=порядок.название if порядок else None)
        писать = self.склад is not None if писать is None else писать

        for номер in range(с_какой, с_какой + страниц):
            ссылка = self._ссылка(путь, собранное.код if собранное else None,
                                  порядок.код if порядок else None, номер)
            тело, конечный, код = await self._страница(ссылка)

            if not detect.каталог(тело):
                if detect.выдача(тело):
                    break                       # объявлений нет — дальше листать нечего
                raise НеопознаннаяСтраница(
                    f"вместо выдачи пришло незнакомое: код {код}, конечный адрес {конечный}")

            # Сотая страница молча приводит на первую: Авито возвращает адрес без номера.
            if номер > 1 and _номер_страницы(конечный) != номер:
                break

            состояние = состояние_выдачи(тело)
            if собранное:
                беды = filters.сверить(собранное, состояние)
                if беды:
                    raise ФильтрНеПрименился("; ".join(беды))
            if порядок and filters.сортировка_применилась(состояние, порядок.код) is False:
                raise ФильтрНеПрименился(
                    f"сортировку «{порядок.название}» (s={порядок.код}) Авито выбросил: "
                    f"страница пришла обычная, порядок в ней обычный")

            разобрано = разобрать_выдачу(состояние)
            итог.объявления += разобрано["объявления"]
            итог.всего = разобрано.get("нашлось")
            итог.страниц_всего = разобрано.get("страниц")
            итог.страницы.append(номер)
            self._сказать(Событие("страница", ссылка, "каталог", код, self._имя, тело,
                                  объявлений=len(разобрано["объявления"])))

            if писать and self.склад:
                записано = await self.склад.записать_выдачу(
                    разобрано, ключ=self._ключ(путь, собранное, порядок), ссылка=ссылка,
                    страница=номер, фильтры=собранное.описание if собранное else None,
                    сортировка=порядок.название if порядок else None, адрес=self._имя)
                if записано["изменений"]:
                    self._сказать(Событие("записано", ссылка, "изменения", код, self._имя,
                                          подробности=f"событий {записано['изменений']}"))

        итог.запросов = self._запросов
        return итог

    async def карточки(self, номера: Iterable[str | int], *,
                       писать: bool | None = None) -> Карточки:
        """Забрать карточки по номерам объявлений.

        Ходим через /items/{номер}: Авито сам уведёт на карточку, и такой путь мягче к
        адресу, чем заход сразу по длинной ссылке.
        """
        итог = Карточки(карточки=[])
        писать = self.склад is not None if писать is None else писать

        for номер in номера:
            ссылка = f"/items/{номер}"
            тело, конечный, код = await self._страница(ссылка)

            if not detect.карточка(тело):
                если_снято = (код == 404 or "/not-found" in (конечный or "")
                              or _путь(конечный).startswith("/auto-journal"))
                if если_снято:
                    raise ОбъявлениеСнято(
                        f"объявления {номер} больше нет: увели на {конечный}")
                raise НеопознаннаяСтраница(
                    f"по номеру {номер} пришло незнакомое: код {код}, "
                    f"конечный адрес {конечный}")

            карточка = разобрать_карточку(тело, ref=dt.datetime.now(dt.timezone.utc))
            итог.карточки.append(карточка)
            self._сказать(Событие("карточка", ссылка, "карточка", код, self._имя, тело,
                                  подробности=(карточка.get("заголовок") or "")[:60]))
            if писать and self.склад:
                await self.склад.записать_карточку(карточка, адрес=self._имя)

        итог.запросов = self._запросов
        return итог

    # ------------------------------------------------------------------ внутреннее

    @property
    def _имя(self) -> str:
        return self._адрес.имя if self._адрес else ""

    @staticmethod
    def _ссылка(путь: str, код: str | None, сортировка: str | None, страница: int) -> str:
        части = ([f"f={код}"] if код else []) + ([f"s={сортировка}"] if сортировка else [])
        части += [f"p={страница}"] if страница > 1 else []
        разделитель = "&" if "?" in путь else "?"
        return путь + (разделитель + "&".join(части) if части else "")

    @staticmethod
    def _ключ(путь: str, собранное, порядок) -> str:
        """Устойчивое имя задачи для базы: по адресу опознавать нельзя, в нём код фильтра.

        Сортировка входит в имя: тот же срез, разложенный иначе, — это другой поиск,
        и позиции в нём другие. Слепи мы их в один, страницы в находках перетирались бы
        при каждом прогоне.

        Она входит кодом, а не словами, потому что слова у неё двоятся: за общими
        сортировками мы на страницу не ходим и зовём их по-своему («по дате»), а сходив
        за справочником — по-авитовски («По дате»). Один и тот же поиск получил бы два
        ключа. Словесное описание живёт в самой записи запроса, там оно и нужно.
        """
        return (путь + (f" | {собранное.описание}" if собранное else "")
                + (f" | s={порядок.код}" if порядок else ""))

    async def _взять_адрес(self) -> Адрес:
        if self._адрес is None:
            self._адрес = await self.адреса.взять()
        if self._адрес is None:
            raise АдресаКончились("свободных адресов не осталось, задача не доделана")
        return self._адрес

    async def _сменить_адрес(self, исход: str, ссылка: str, подробности: str = ""):
        if self._адрес is not None:
            self._сказать(Событие("адрес выбыл", ссылка, исход, None, self._имя,
                                  подробности=подробности))
            await self.адреса.вернуть(self._адрес, исход)
            self._адрес = None

    async def _страница(self, ссылка: str) -> tuple[str, str, int | None]:
        """Один запрос: со сменой адреса на барьерах и повторами на обрывах."""
        while True:
            адрес = await self._взять_адрес()
            ответ = await self._достать(адрес, ссылка)
            if ответ is None:
                await self._сменить_адрес("молчит", ссылка)
                continue
            тело, конечный, код = ответ

            if detect.заглушка(тело):
                self._сказать(Событие("адрес выбыл", ссылка, "заглушка", код,
                                      self._имя, тело))
                await self.адреса.вернуть(адрес, "заглушка")
                self._адрес = None
                continue

            if detect.барьер(тело):
                какой = barriers.вид(тело)
                self._сказать(Событие("барьер", ссылка, какой, код, self._имя, тело))
                # повторяем туда, где нас остановили: барьер часто встречает уже после
                # редиректа, а исходная ссылка второй раз отвечает «не найдено»
                исход = await barriers.пройти(адрес.сессия, конечный or ссылка, тело)
                self._запросов += исход.запросов
                if not исход.прошли:
                    await self._сменить_адрес(какой, ссылка, исход.что)
                    continue
                return исход.страница, исход.конечный or ссылка, исход.код

            return тело, конечный, код

    async def _достать(self, адрес: Адрес, ссылка: str):
        for _ in range(ПОВТОРОВ_НА_ОБРЫВЕ):
            self._запросов += 1
            try:
                полная = BASE + ссылка if ссылка.startswith("/") else ссылка
                ответ = await адрес.сессия.get(полная)
                return (ответ.text, str(getattr(ответ, "url", "") or ссылка),
                        ответ.status_code)
            except Exception as e:  # noqa: BLE001 — любой обрыв транспорта
                self._сказать(Событие("обрыв", ссылка, type(e).__name__, None, адрес.имя,
                                      подробности=str(e)[:120]))
        return None
