"""Ошибки библиотеки. Все — критические: работаем жёстко.

Барьеры, обрывы и смена адреса ошибками не считаются — это обычная работа, и наружу
они не выходят. Наружу выходит только то, после чего продолжать нельзя, не рискуя
записать неправду: неопознанная страница, невыставленный фильтр, поехавший разбор,
кончившиеся адреса, снятое объявление.

Ловить можно одним `КритическаяОшибка` — остальные наследуются от неё.
"""
from __future__ import annotations

__all__ = ["КритическаяОшибка", "НеопознаннаяСтраница", "ФильтрНеПрименился",
           "ОшибкаРазбора", "АдресаКончились", "ОбъявлениеСнято",
           "НетТакогоФильтра", "УпрямыйФильтр"]


class КритическаяОшибка(RuntimeError):
    """Продолжать нельзя. Общий предок всех ошибок библиотеки."""


class НеопознаннаяСтраница(КритическаяОшибка):
    """Пришло что-то, чего не знает ни один детектор.

    Самая важная из всех: молча принять незнакомую страницу за данные — значит месяц
    писать в базу мусор и узнать об этом последним.
    """


class ФильтрНеПрименился(КритическаяОшибка):
    """Авито отдал выдачу, но без запрошенного фильтра.

    Так бывает по-настоящему: страница приходит обычной, счётчик не меняется, а фильтра
    в ней нет. Если это проглотить, мы обойдём совсем не то, что просили.
    """


class ОшибкаРазбора(КритическаяОшибка):
    """Разметка страницы поехала: обязательных полей нет или брака слишком много."""


class АдресаКончились(КритическаяОшибка):
    """Свободных адресов не осталось, а задача не доделана.

    Возвращать половину нельзя: недобор молча превратится в «нашли двести объявлений»
    там, где их пять тысяч.
    """


class ОбъявлениеСнято(КритическаяОшибка):
    """Объявления больше нет — Авито увёл в журнал или на «не найдено».

    Пока это критическая ошибка: обработки снятых нет. Когда она появится, задача
    перестанет падать и будет возвращать такие номера отдельным списком.
    """


class НетТакогоФильтра(КритическаяОшибка, KeyError):
    """В справочнике страницы нет такого фильтра или значения."""


class УпрямыйФильтр(КритическаяОшибка, NotImplementedError):
    """Фильтр известен, но в компактном коде он не работает — проверено вживую."""
